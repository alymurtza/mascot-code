"""Writes src/shared/themes.ts: every theme's colour tokens (20 regular, 15 special),
contrast-checked (WCAG 2). Usage: python3 -I gen_themes_ts.py <themes.json> <out.ts>"""
import json, sys, importlib.util

spec = importlib.util.spec_from_file_location('t', sys.argv[0].replace('gen_themes_ts.py', 'themes.py'))
# themes.py runs its own generation on import; load only its helpers by exec'ing the top part.
src = open(sys.argv[0].replace('gen_themes_ts.py', 'themes.py')).read().split('# name, accent, surface hue')[0]
ns = {}
exec(src, ns)
oklch_to_hex, hex_to_oklch, contrast, shift_until, rgba = ns['oklch_to_hex'], ns['hex_to_oklch'], ns['contrast'], ns['shift_until'], ns['rgba']

regular = json.load(open(sys.argv[1]))
ORDER = ['cream', 'rose', 'ember', 'champagne', 'sunflower', 'forest', 'mint', 'ocean', 'blue', 'violet']

def nets_for(accent, dark, bg, solid):
    _, _, ah = hex_to_oklch(accent)
    picks = []
    def dist(a, b):
        d = abs(a - b) % 360; return min(d, 360 - d)
    for h in [150, 245, 310, 25, 85, 195]:
        if dist(h, ah) >= 45 and all(dist(h, p) >= 60 for p in picks): picks.append(h)
        if len(picks) == 3: break
    out = []
    for h in picks:
        c = oklch_to_hex(.72 if dark else .56, .15, h)
        c = shift_until(c, bg, 3.0, 1 if dark else -1); c = shift_until(c, solid, 3.0, 1 if dark else -1)
        out.append(c)
    return dict(zip(('n-wifi', 'n-eth', 'n-usb'), out))

SPECIAL = [  # key, name, dark?, page colour, accent
    ('aurora', 'Aurora', True, '#04100f', '#14a88c'),
    ('meteor', 'Meteor shower', True, '#0c0716', '#ff8f6b'),
    ('jellyfish', 'Jellyfish', True, '#030c1a', '#ff8ad8'),
    ('lanterns', 'Sky lanterns', True, '#0d0a1c', '#ffb547'),
    ('stillnight', 'Still night', True, '#07191d', '#ff8a4c'),
    ('nightgarden', 'Night garden', True, '#08191b', '#e98cb0'),
    ('glowkoi', 'Glow koi', True, '#040c0e', '#ff7a45'),
    ('blossom', 'Cherry blossom', False, '#fdf2f4', '#e0607e'),
    ('mountains', 'Misty mountains', False, '#eef2f6', '#4a6fa5'),
    ('dunes', 'Desert dunes', False, '#fbf2e4', '#c8862a'),
    ('bamboo', 'Bamboo grove', False, '#f1f6ea', '#4f9a3a'),
    ('koi', 'Koi pond', False, '#e6f4f1', '#e8632b'),
    ('garden', 'Garden pond', False, '#e3f4ee', '#d2557f'),
    ('reeds', 'Reed corner', False, '#e8f3e3', '#a85625'),
    ('balloons', 'Hot air balloons', False, '#f6f1ea', '#e2475b'),
]

def special_tokens(base, accent, dark):
    _, C, H = hex_to_oklch(base)
    c = min(C, .03)
    if dark:
        Ls = dict(solid=.2, raised=.235, line=.32, **{'line-soft': .27}, ink=.95, muted=.76, faint=.62)
    else:
        Ls = dict(solid=.995, raised=.985, line=.89, **{'line-soft': .93}, ink=.24, muted=.46, faint=.57)
    t = {'bg': base}
    for k, L in Ls.items(): t[k] = oklch_to_hex(L, c * (.5 if k == 'ink' else 1), H)
    t['accent'] = accent
    L, Ca, Ha = hex_to_oklch(accent)
    t['accent-2'] = oklch_to_hex(min(.93, L + .12), Ca * .8, Ha)
    dark_ink = oklch_to_hex(.18, .03, Ha)
    t['accent-ink'] = dark_ink if contrast(accent, dark_ink) >= contrast(accent, '#ffffff') else '#ffffff'
    text = shift_until(accent, t['bg'], 4.5, 1 if dark else -1); text = shift_until(text, t['solid'], 4.5, 1 if dark else -1)
    text = shift_until(text, t['raised'], 4.5, 1 if dark else -1)
    t['accent-text'] = text
    t['accent-soft'] = rgba(accent, '.15'); t['glow'] = rgba(accent, '.09')
    t.update(nets_for(accent, dark, t['solid'], t['raised']))
    return t

CHECKS = [('ink', 'raised', 7), ('ink', 'solid', 7), ('muted', 'raised', 4.5), ('muted', 'solid', 4.5), ('faint', 'solid', 3),
          ('accent-ink', 'accent', 4.5), ('accent-text', 'solid', 4.5), ('accent-text', 'raised', 4.5),
          ('n-wifi', 'solid', 3), ('n-eth', 'solid', 3), ('n-usb', 'solid', 3)]

themes, failed = [], []
for key in ORDER:
    for mode in ('light', 'dark'):
        t = dict(regular[key][mode]); t['glow'] = rgba(t['accent'], '.09'); t['accent-soft'] = rgba(t['accent'], '.15')
        themes.append((f'{key}-{mode}', regular[key]['name'], mode == 'dark', False, t))
for key, name, dark, base, accent in SPECIAL:
    themes.append((key, name, dark, True, special_tokens(base, accent, dark)))
for key, name, dark, special, t in themes:
    for fg, bg, m in CHECKS:
        r = contrast(t[fg], t[bg])
        if r < m: failed.append(f'{key}: {fg} on {bg} = {r:.2f} < {m}')

ORDER_KEYS = ['bg', 'solid', 'raised', 'line', 'line-soft', 'ink', 'muted', 'faint', 'accent', 'accent-2', 'accent-ink',
              'accent-text', 'accent-soft', 'glow', 'n-wifi', 'n-eth', 'n-usb']
lines = ['// Generated by a contrast-checking script (WCAG 2): body text 7:1, other text and accent',
         '// text 4.5:1, network colours 3:1. Cream is the app icon\'s colour.',
         "import type { Palette } from './settings'", '',
         'export interface Theme {', '  name: string', '  dark: boolean', '  /** Unlocked with the secret keys; has a moving backdrop. */',
         '  special: boolean', '  tokens: Record<string, string>', '}', '',
         'export const THEMES: Record<Palette, Theme> = {']
for key, name, dark, special, t in themes:
    k = f"'{key}'" if '-' in key else key
    lines.append(f"  {k}: {{\n    name: '{name}',\n    dark: {str(dark).lower()},\n    special: {str(special).lower()},\n    tokens: {{")
    lines += [f"      '{tk}': '{t[tk]}'," for tk in ORDER_KEYS]
    lines[-1] = lines[-1].rstrip(',')
    lines.append('    }\n  },')
lines[-1] = lines[-1].rstrip(',')
lines.append('}')
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
for f in failed: print('FAIL', f)
print(f'{len(themes)} themes, {len(failed)} failed checks')
sys.exit(1 if failed else 0)
